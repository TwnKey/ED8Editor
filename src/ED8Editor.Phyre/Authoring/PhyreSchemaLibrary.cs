    private static readonly Dictionary<string, ClassRow> ByName =
        Rows.ToDictionary(row => row.Name, StringComparer.Ordinal);

    /// <summary>The names of every class the library describes.</summary>
    public static IReadOnlyCollection<string> ClassNames => ByName.Keys;

    /// <summary>The primitive type names the corpus uses, for reference.</summary>
    public static IReadOnlyList<string> PrimitiveTypeNames => PrimitiveTypes;

    public static bool Knows(string className) => ByName.ContainsKey(className);

    /// <summary>
    /// Whether the engine treats this class as a header class — the flag that
    /// puts an entry in the header class section and lets its objects be bigger
    /// than the class itself. Only two classes in the game carry it.
    /// </summary>
    public static bool IsHeaderClass(string className)
        => ByName.TryGetValue(className, out var row) && (row.Flags & 4) != 0;

    /// <summary>
    /// Every class this one drags in: the one it derives from, and the class of
    /// each of its members. A cluster that lists a class has to list these too,
    /// since its own descriptors point at them by index.
    /// </summary>
    public static IEnumerable<string> Referenced(string className)
    {
        if (!ByName.TryGetValue(className, out var row)) yield break;
        if (row.SuperClassName != "-") yield return row.SuperClassName;
        foreach (var member in row.Members)
        {
            if (ByName.ContainsKey(member.TypeName)) yield return member.TypeName;
        }
    }

    /// <summary>
    /// Builds the class table a cluster would carry, for the types and classes it
    /// lists and in the order it lists them. Order is the caller's to choose: the
    /// descriptors keep it, while the packed namespace stores the names sorted.
    /// </summary>
    public static PhyreClassDescriptor[] Descriptors(
        IReadOnlyList<string> typeNames,
        IReadOnlyList<string> classNames)
    {
        ArgumentNullException.ThrowIfNull(typeNames);
        ArgumentNullException.ThrowIfNull(classNames);

        var typeIds = new Dictionary<string, uint>(StringComparer.Ordinal);
        for (var index = 0; index < typeNames.Count; index++) typeIds[typeNames[index]] = (uint)index;
        var classIds = new Dictionary<string, uint>(StringComparer.Ordinal);
        for (var index = 0; index < classNames.Count; index++) classIds[classNames[index]] = (uint)index;

        var descriptors = new PhyreClassDescriptor[classNames.Count];
        var memberIndex = 0;
        for (var index = 0; index < classNames.Count; index++)
        {
            if (!ByName.TryGetValue(classNames[index], out var row))
            {
                throw new InvalidOperationException(
                    $"The schema library does not describe '{classNames[index]}'.");
            }

            var members = new PhyreDataMember[row.Members.Length];
            for (var member = 0; member < members.Length; member++, memberIndex++)
            {
                var source = row.Members[member];
                members[member] = new PhyreDataMember(
                    memberIndex,
                    member,
                    source.Name,
                    TypeId(source.TypeName, typeIds, classIds, typeNames.Count),
                    source.TypeName,
                    source.ValueOffset,
                    source.Size,
                    source.Flags,
                    source.FixedArraySize);
            }

            descriptors[index] = new PhyreClassDescriptor(
                index,
                row.Name,
                SuperClassId(row.SuperClassName, classIds),
                row.Size,
                row.Alignment,
                (uint)members.Length,
                row.OffsetFromParent,
                row.OffsetToBase,
                row.OffsetToBaseInAllocatedBlock,
                row.Flags,
                row.DefaultBufferOffset,
                members);
        }
        return descriptors;
    }

    /// <summary>Where a member sits in its class, by name.</summary>
    public static uint MemberOffset(string className, string memberName)
    {
        if (!ByName.TryGetValue(className, out var row))
        {
            throw new InvalidOperationException($"The schema library does not describe '{className}'.");
        }
        foreach (var member in row.Members)
        {
            if (member.Name == memberName) return member.ValueOffset;
        }
        throw new InvalidOperationException($"'{className}' has no member '{memberName}'.");
    }

    /// <summary>How big an instance of a class is.</summary>
    public static uint SizeOf(string className)
        => ByName.TryGetValue(className, out var row)
            ? row.Size
            : throw new InvalidOperationException($"The schema library does not describe '{className}'.");

    private static uint SuperClassId(string name, IReadOnlyDictionary<string, uint> classIds)
    {
        if (name == "-") return 0;
        if (classIds.TryGetValue(name, out var id)) return id + 1;
        throw new InvalidOperationException(
            $"The superclass '{name}' is not among the classes the cluster lists.");
    }

    private static uint TypeId(
        string name,
        IReadOnlyDictionary<string, uint> typeIds,
        IReadOnlyDictionary<string, uint> classIds,
        int typeCount)
    {
        if (typeIds.TryGetValue(name, out var type)) return type;
        if (classIds.TryGetValue(name, out var id)) return (uint)typeCount + 1 + id;
        throw new InvalidOperationException(
            $"The member type '{name}' is neither a type nor a class the cluster lists.");
    }
