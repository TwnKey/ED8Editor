/// <summary>
/// Every class the game's clusters describe, as data rather than as bytes copied
/// from one of its files.
///
/// A cluster carries the layout of the classes it uses — the size and alignment
/// of each, the offset, size and flags of each member. Those are facts about the
/// engine, not about the file: measured over the 32 796 clusters the game ships,
/// 175 classes and 521 members appear, and <b>no class is ever described two
/// different ways</b>. So one library can serve every cluster, and a model can be
/// written without opening a model.
///
/// The library speaks <b>names</b>, never ids. Inside a cluster a class or a type
/// is an index into that cluster's own tables, so an id means nothing once it
/// leaves the file it came from. The engine resolves those indices in
/// <c>PhyreNamespacePacked.cpp</c>: a member's type id below the type count names
/// a type, at or above it names <c>class[id - typeCount - 1]</c>; a superclass id
/// is one-based over the classes alone, zero meaning none. <see cref="Descriptors"/>
/// applies that rule in reverse.
///
/// Generated by <c>--emit-library</c> and checked back against the game: the
/// namespace this table produces for a shipped cluster has to be, byte for byte,
/// the one that cluster carries.
/// </summary>
